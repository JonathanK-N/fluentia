import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { execFileSync } from "node:child_process";
import path from "node:path";

test("inscription, courriel, session, lecture persistante et résultat privé sur API réelle", async ({page, browser}, info) => {
  const email = `student-${info.project.name}-${Date.now()}@example.test`;
  const password = "Lecture!Orbite-7294";
  await page.goto("/etudiant/compte");
  await page.getByRole("button", {name: "Inscription", exact: true}).click();
  await page.getByLabel("Prénom ou nom d’usage").fill("Camille de recette");
  await page.getByLabel("Adresse e-mail", {exact: true}).fill(email);
  await page.getByLabel("Mot de passe", {exact: true}).fill(password);
  await page.getByRole("button", {name: "Créer mon compte", exact: true}).click();
  await expect(page.getByRole("status")).toContainText("message de vérification");
  // Lecture de la boîte locale du serveur, aucune route exposant les jetons.
  const script = `import pathlib,email,re,sys; root=pathlib.Path(sys.argv[1]); messages=[email.message_from_bytes(p.read_bytes()) for p in root.glob('*')]; m=next(m for m in messages if sys.argv[2] in m.get('To','')); body=m.get_payload(decode=True).decode('utf-8'); print(re.search(r'http[^\\s]+',body).group(0))`;
  const verification = execFileSync(process.env.E2E_PYTHON || "python", ["-c", script, process.env.DJANGO_EMAIL_FILE_PATH!, email], {encoding: "utf8"}).trim();
  await page.goto(verification);
  await page.getByRole("button", {name: "Vérifier mon adresse", exact: true}).click();
  await expect(page.getByRole("status")).toContainText("Adresse vérifiée");
  await expect(page).not.toHaveURL(/token=/);
  await page.getByRole("link", {name: "Aller à mon compte", exact: true}).click();
  await page.getByLabel("Adresse e-mail", {exact: true}).fill(email);
  await page.getByLabel("Mot de passe", {exact: true}).fill(password);
  await page.getByRole("button", {name: "Se connecter", exact: true}).click();
  await expect(page.getByRole("heading", {name: "Mon profil étudiant"})).toBeVisible();
  await page.getByLabel("Prénom ou nom d’usage").fill("Camille");
  await page.getByRole("button", {name: "Enregistrer mon profil"}).click();
  await expect(page.getByRole("status")).toContainText("profil est enregistré");
  await page.getByRole("link", {name: "Choisir un exercice"}).click();
  await page.getByRole("article").filter({has: page.getByRole("heading", {name: "Lecture de recette — atelier vélo", exact: true})}).getByRole("button", {name: "Commencer cet exercice"}).click();
  await expect(page).toHaveURL(/\/etudiant\/lecture\//);
  const attemptUrl = page.url();
  const attemptId = attemptUrl.split("/").pop();
  await expect(page.getByRole("radio", {name: "Les pièces à remplacer", exact: true})).toBeVisible();
  const noCsrf = await page.request.post(`/api/v1/attempts/${attemptId}/submit/`);
  expect(noCsrf.status()).toBe(403);
  const premature = await page.request.get(`/api/v1/attempts/${attemptId}/results/`);
  expect(premature.status()).toBe(409);
  const outsider = await browser.newContext();
  expect((await outsider.request.get(`http://127.0.0.1:3101/api/v1/attempts/${attemptId}/`)).status()).toBe(403);
  await outsider.close();
  const other = await browser.newContext();
  const bootstrap = await other.request.get("http://127.0.0.1:3101/api/v1/auth/csrf/");
  const csrf = (await bootstrap.json()).csrf_token;
  const otherEmail = `other-${email}`;
  expect((await other.request.post("http://127.0.0.1:3101/api/v1/auth/register/", {data: {email: otherEmail, password, display_name: "Autre compte de recette"}, headers: {"X-CSRFToken": csrf}})).status()).toBe(202);
  expect((await other.request.post("http://127.0.0.1:3101/api/v1/auth/login/", {data: {email: otherEmail, password}, headers: {"X-CSRFToken": csrf}})).status()).toBe(200);
  expect((await other.request.get(`http://127.0.0.1:3101/api/v1/attempts/${attemptId}/`)).status()).toBe(404);
  expect((await other.request.get(`http://127.0.0.1:3101/api/v1/attempts/${attemptId}/results/`)).status()).toBe(404);
  expect((await (await other.request.get("http://127.0.0.1:3101/api/v1/attempts/")).json()).count).toBe(0);
  await other.close();
  await page.route("**/api/v1/attempts/*/answers/", route => route.abort());
  await page.getByRole("radio", {name: "Une preuve de paiement", exact: true}).click();
  await expect(page.getByRole("main").getByRole("alert")).toContainText("Connexion interrompue");
  await expect(page.getByRole("radio", {name: "Une preuve de paiement", exact: true})).not.toBeChecked();
  await page.unroute("**/api/v1/attempts/*/answers/");
  await page.getByRole("radio", {name: "Les pièces à remplacer", exact: true}).focus();
  await page.keyboard.press("Space");
  await expect(page.getByRole("status")).toContainText("Réponse enregistrée");
  await expect(page.getByRole("radio", {name: "Les pièces à remplacer", exact: true})).toBeFocused();
  await page.reload();
  await expect(page.getByRole("radio", {name: "Les pièces à remplacer", exact: true})).toBeChecked();
  await page.getByRole("link", {name: "Retour aux exercices"}).click();
  await page.getByRole("link", {name: /Reprendre/}).click();
  await expect(page).toHaveURL(attemptUrl);
  await expect(page.getByRole("heading", {name: "À vous de lire", exact: true})).toBeVisible();
  await expect(page).toHaveTitle(/Compréhension écrite/);
  await expect(page.getByRole("radio", {name: "Les pièces à remplacer", exact: true})).toBeChecked();
  await page.evaluate(() => document.fonts.ready.then(() => undefined));
  await page.screenshot({path: info.outputPath("lecture.png"), fullPage: true});
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect((await new AxeBuilder({page}).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.getByRole("button", {name: "Changer le thème"}).click();
  expect((await new AxeBuilder({page}).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.screenshot({path: info.outputPath("lecture-sombre.png"), fullPage: true});
  await page.getByRole("button", {name: "Changer le thème"}).click();
  await page.getByRole("button", {name: "Terminer et vérifier mes réponses"}).click();
  await page.getByRole("button", {name: "Confirmer la soumission"}).click();
  await expect(page.getByRole("heading", {name: "Votre résultat", exact: true})).toBeVisible();
  await expect(page.getByText("1 / 1", {exact: true})).toBeVisible();
  await expect(page.getByText(/Réponse attendue : Les pièces à remplacer/)).toBeVisible();
  await page.reload();
  await expect(page.getByText("1 / 1", {exact: true})).toBeVisible();
  await page.screenshot({path: info.outputPath("resultat.png"), fullPage: true});
  await page.getByRole("link", {name: "Mon compte", exact: true}).click();
  await page.getByRole("button", {name: "Se déconnecter"}).click();
  await expect(page.getByRole("heading", {name: "Content de vous retrouver"})).toBeVisible();
  expect(path.isAbsolute(process.env.DJANGO_EMAIL_FILE_PATH!)).toBe(true);
});
